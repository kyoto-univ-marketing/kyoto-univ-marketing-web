export interface Member {
    /** 役割の英字表記。装飾として小さく置く */
    en: string
    /** 役割の日本語表記。SEOの実体なので必ず本文に残す */
    role: string
    name: string
    reading: string
    /** 所属学部と入学年。「経済学部 2021年入学」の形で表示する */
    faculty: string
    enrolledYear: number
    image: typeof SakodaImg
    /** 京大マーケティング研究所を一言で */
    catchphrase: string
    /** 一言の説明 */
    lead: string[]
    /** 入会を考えている方へ */
    message: string[]
    /** 個別ページがある場合の遷移先 */
    detailHref?: string
}

/**
 * 発起人の本文を組み立てる部品。
 *
 * 見出しは立てない。本人の語りなので、章立てにすると報告書の口調になる。
 * 代わりに、要になる一段を紺の帯にして、そこで話を区切る。
 *
 * 歴代代表は短いので `lead` のまま。
 */
export type FounderBlock =
    /** ふつうの本文。白地に黒 */
    | { kind: 'text'; body: string[] }
    /**
     * 紺地に白抜きの一段。長い本文の区切りと、要点の強調を兼ねる。
     * withKakejiku は掛け軸の写真を横に並べる。中身と対応する段だけに付けること。
     */
    | { kind: 'band'; text: string; withKakejiku?: boolean }

export interface Founder extends Omit<Member, 'lead'> {
    story: FounderBlock[]
}

